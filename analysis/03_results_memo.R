# =====================================================================
# 03_results_memo.R -- writes analysis/RESULTS_CONFIRMED_DATES.md from
# analysis/output/ (no numbers typed by hand). Tables follow the layout
# of the thesis tables they replace.
# =====================================================================

suppressPackageStartupMessages(library(data.table))
OUT  <- "analysis/output"
OUTC <- c(ln_area = "Area", ln_yield = "Yield", ln_production = "Production")
mn   <- function(x) sub("^-", "−", x)
f3   <- function(x) mn(sprintf("%.3f", x))
star <- function(p) ifelse(p < 0.01, "***", ifelse(p < 0.05, "**", ifelse(p < 0.10, "*", "")))
cell <- function(d, o) { r <- d[outcome == o]; c(paste0(f3(r$est), star(r$p)), sprintf("(%s)", f3(r$se)),
                                                 sprintf("[%s, %s]", f3(r$ci_lo), f3(r$ci_hi)), sprintf("p = %s", f3(r$p))) }
panel_md <- function(d, title) {
  m <- sapply(names(OUTC), function(o) cell(d, o))
  c(sprintf("| *%s* | | | |", title),
    sprintf("| Contrast | %s |", paste(m[1, ], collapse = " | ")),
    sprintf("| | %s |", paste(m[2, ], collapse = " | ")),
    sprintf("| | %s |", paste(m[3, ], collapse = " | ")),
    sprintf("| | %s |", paste(m[4, ], collapse = " | ")),
    sprintf("| Comparison series | %s |", paste(d[match(names(OUTC), outcome), n_comparison], collapse = " | ")))
}
hdr <- c("| | (1) Area | (2) Yield | (3) Production |", "|---|---|---|---|")

T3 <- fread(file.path(OUT, "table3_timing.csv")); T4 <- fread(file.path(OUT, "table4_main.csv"))
T5 <- fread(file.path(OUT, "table5_sensitivity.csv")); T6 <- fread(file.path(OUT, "table6_area_weights.csv"))
W6 <- fread(file.path(OUT, "table6_weights.csv")); TA1 <- fread(file.path(OUT, "tableA1_leave_one_out.csv"))
J6 <- fread(file.path(OUT, "fig6_joint_pretest.csv")); MC <- fread(file.path(OUT, "fig6_joint_pretest_mc.csv"))
F7 <- fread(file.path(OUT, "fig7_crop_means.csv")); T2 <- fread(file.path(OUT, "table2_summary.csv"))
T9 <- fread(file.path(OUT, "table9_prepilot_growth.csv"))
NAME <- c(soybean = "Soybean", onion = "Onion", sweet_potato = "Sweet potato", corn = "Corn", garlic = "Garlic",
          spring_potato = "Spring potato", red_pepper = "Red pepper")

L <- c("# National crop analysis with confirmed insurance dates",
  "",
  "Generated by `analysis/03_results_memo.R` from `analysis/output/` (run `analysis/01_*.R`, `02_*.R`, `03_*.R`).",
  "Estimator, reference year, comparison rules and inference are those of the thesis (equations 4-6, Appendix A);",
  "9,999 Webb multiplier draws, seed 20261021. *Main* = six treated crops with confirmed expansion years;",
  "*S1* = seven crops with spring potato under its previous coding; *S2* = previous thesis coding (seven crops,",
  "Yearbook main-program years). The rice analysis (Tables 7-8, Figure 8) is not re-estimated here.",
  "",
  "## Table 3. Insurance timing",
  "",
  "| Crop | Pilot year | Expansion year (main) | Previous expansion year | Product-table year | Reference year | Transition years (main) |",
  "|---|---|---|---|---|---|---|",
  T3[, sprintf("| %s | %d | %s | %d | %d | %d | %s |", crop, pilot_year,
               fifelse(in_main, as.character(expansion_year_main), "excluded"), previous_expansion_year,
               product_table_year, reference_year, fifelse(in_main, as.character(transition_years_main), "–"))],
  "",
  "## Figure 6. Joint pre-pilot test (sum of squared standardized contrasts, e = −10 to −2)",
  "",
  "| Design | Outcome | Statistic | p | p range over 20 further draw sets |", "|---|---|---|---|---|",
  merge(J6, MC, by = c("design", "outcome"))[order(-(design == "main"), match(outcome, names(OUTC))),
    sprintf("| %s | %s | %.2f | %s | %s–%s |", design, OUTC[outcome], stat, f3(p), f3(p_min), f3(p_max))],
  "",
  "## Table 4. Mean post-period contrasts")
for (k in c("main", "S1", "S2")) {
  L <- c(L, "", sprintf("**Design %s**", k), "", hdr,
         panel_md(T4[design == k & substr(spec, 1, 1) == "A"], "Panel A. Full comparison pool"),
         panel_md(T4[design == k & substr(spec, 1, 1) == "B"], "Panel B. Excluding two spring series"))
}
L <- c(L, "", "## Table 5. Sensitivity (main design)", "", hdr)
for (s in unique(T5$spec)) L <- c(L, head(panel_md(T5[spec == s], paste("Panel", s)), 5))
L <- c(L, "", "## Table 6. Pre-pilot area weights (main design)", "", hdr,
       panel_md(T6[substr(spec, 1, 1) == "A"], "Panel A. Full comparison pool"),
       panel_md(T6[substr(spec, 1, 1) == "B"], "Panel B. Excluding two spring series"), "",
       paste0("Area weights (mean cultivated area 2003–2007): ",
              paste(W6[, sprintf("%s %.1f", NAME[crop_id], 100 * weight)], collapse = ", "),
              sprintf(" percent; equal weights are %.1f percent.", 100 / nrow(W6))))
L <- c(L, "", "## Table A1. Leave one crop out (main design)", "",
       "| Omitted crop | (1) Area | (2) Yield | (3) Production |", "|---|---|---|---|",
       TA1[, .(v = paste0(f3(est), star(p))), by = .(omitted, outcome)][
         , .(row = sprintf("| %s | %s |", NAME[omitted[1]], paste(v[match(names(OUTC), outcome)], collapse = " | "))), by = omitted]$row)
L <- c(L, "", "## Figure 7. Crop-specific mean contrasts, event years 0–9", "",
       "| Crop | Pool | Area | Yield | Production |", "|---|---|---|---|---|",
       F7[, .(v = f3(est)), by = .(crop_id, pool, outcome)][
         , .(row = sprintf("| %s | %s | %s |", NAME[crop_id[1]], pool[1], paste(v[match(names(OUTC), outcome)], collapse = " | "))),
         by = .(crop_id, pool)]$row)
L <- c(L, "", "## Table 2. Summary statistics (main design)", "",
       "| Variable | Group | Mean | S.D. | Min. | Max. | Obs. | Crops |", "|---|---|---|---|---|---|---|---|",
       T2[, sprintf("| %s | %s | %s | %s | %s | %s | %d | %d |", variable, group, format(round(mean), big.mark = ","),
                    format(round(sd), big.mark = ","), format(round(min), big.mark = ","), format(round(max), big.mark = ","), obs, crops)])
L <- c(L, "", "## Table 9. Pre-pilot growth, 1998–2007 (main design)", "",
       "| Outcome | Treated mean (S.D.) | Comparison mean (S.D.) | Difference | Std. difference | Crops (T / C) |", "|---|---|---|---|---|---|",
       T9[, sprintf("| %s | %s (%s) | %s (%s) | %s | %s | %d / %d |", OUTC[variable], f3(m_t), f3(sd_t), f3(m_c), f3(sd_c),
                    f3(diff), f3(std_diff), n_t, n_c)])
writeLines(L, "analysis/RESULTS_CONFIRMED_DATES.md")
cat("wrote analysis/RESULTS_CONFIRMED_DATES.md (", length(L), "lines )\n")
